def project_ids_to_scan(selected_project: str | None) -> list[str]:
    if selected_project:
        return [selected_project]
    if not PROJECTS_ROOT.exists():
        return []
    return sorted(entry.name for entry in PROJECTS_ROOT.iterdir() if entry.is_dir() and not entry.name.startswith("."))


def episodes_to_scan(project_id: str, selected_episode: str | None) -> list[str]:
    if selected_episode:
        return [selected_episode]
    episodes_root = PROJECTS_ROOT / project_id / "episodes"
    if not episodes_root.exists():
        return ["epXX"]
    episodes = sorted(
        entry.name
        for entry in episodes_root.iterdir()
        if entry.is_dir() and not entry.name.startswith(".")
    )
    return episodes or ["epXX"]


def command_validate(_: argparse.Namespace) -> int:
    issues = collect_validate_issues()
    if issues:
        for issue in issues:
            prefix = issue.path or "workspace"
            print(f"[{issue.level}] {prefix}: {issue.message}")
        return 1
    print("validation passed")
    return 0


def command_status(args: argparse.Namespace) -> int:
    payload = {"projects": []}
    for project_id in project_ids_to_scan(args.project):
        project_payload = {"project_id": project_id, "episodes": []}
        for episode_id in episodes_to_scan(project_id, args.episode):
            orchestration = build_orchestration_result(project_id, episode_id)
            ledger = build_segment_ledger(project_id, episode_id)
            project_payload["episodes"].append({"orchestration_result": orchestration, "segment_ledger": ledger})
        payload["projects"].append(project_payload)
    print(dump_yaml(payload))
    return 0


def transform_to_compat(text: str) -> str:
    return text.replace("AGENTS.md", "CLAUDE.md").replace(".agents/", ".claude/")


def sync_tree(source_root: Path, target_root: Path) -> None:
    source_files = [path for path in source_root.rglob("*") if path.is_file()]
    source_rel = {path.relative_to(source_root) for path in source_files}
    if target_root.exists():
        for existing in sorted(path for path in target_root.rglob("*") if path.is_file()):
            if existing.relative_to(target_root) not in source_rel:
                existing.unlink()
    target_root.mkdir(parents=True, exist_ok=True)
    for source in source_files:
        relative = source.relative_to(source_root)
        target = target_root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        if source.suffix == ".md":
            target.write_text(COMPAT_NOTICE + transform_to_compat(source.read_text()))
        elif source.suffix == ".json":
            data = json.loads(source.read_text())
            target.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
        else:
            shutil.copy2(source, target)


def command_sync_compat(_: argparse.Namespace) -> int:
    sync_tree(ROOT / ".agents" / "agents", ROOT / ".claude" / "agents")
    sync_tree(ROOT / ".agents" / "skills", ROOT / ".claude" / "skills")
    sync_tree(ROOT / ".agents", ROOT / ".claude")
    claude_md = ROOT / "CLAUDE.md"
    claude_md.write_text(COMPAT_NOTICE + transform_to_compat((ROOT / "AGENTS.md").read_text()))
    print("compat mirror synced")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Workflow guard for the AI 漫剧生产系统")
    subparsers = parser.add_subparsers(dest="command", required=True)

    validate_parser = subparsers.add_parser("validate", help="Validate canonical docs, schemas, and file layout")
    validate_parser.set_defaults(func=command_validate)

    status_parser = subparsers.add_parser("status", help="Read-only project status scan")
    status_parser.add_argument("--project", help="Only scan one project id, for example SER20260424-001")
    status_parser.add_argument("--episode", help="Only scan one episode id, for example ep01")
    status_parser.set_defaults(func=command_status)

    sync_parser = subparsers.add_parser("sync-compat", help="Generate compat mirrors under .claude/")
    sync_parser.set_defaults(func=command_sync_compat)
    return parser


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
