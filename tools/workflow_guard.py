        if creative_path and not compliance_allows(creative_compliance_verdict):
            needs_compliance_review = True
            missing_reviews.append(
                {
                    "review_type": "compliance_review",
                    "target": rel(creative_path),
                    "phase": "stage_gate",
                    "required_before": "进入剧本开发",
                    "verdict": creative_compliance_verdict,
                }
            )
        if needs_business_review or needs_compliance_review:
            next_agent = "business-review-agent / compliance-review-agent"
            next_skill = ""
            next_action = "补齐创意阶段审核 verdict"
            current_goal = "完成创意阶段审核并获得放行 verdict"
